import type { ImageContent, MessageAttribution, ServiceTierByFamily, TextContent } from "@oh-my-pi/pi-ai";
import type { AgentMessage } from "../types";

export interface SessionEntryBase {
	type: string;
	id: string;
	parentId: string | null;
	timestamp: string;
	/** Build identity recorded by coding-agent when it writes the entry. */
	runtime?: RuntimeIdentity;
	/** Off-branch append preserves this active leaf on replay; null records a cleared leaf. */
	activeLeafId?: string | null;
}

/** Build identity stamped on entries written by an omp process. */
export interface RuntimeIdentity {
	/** omp package version. */
	version: string;
	/** Source checkout commit; absent for installed builds. */
	commit?: string;
	/** Source checkout branch; absent on a detached HEAD. */
	branch?: string;
	/** Hash of the checkout's uncommitted tracked changes. */
	diff?: string;
	/** Free-form build label. */
	label?: string;
}

export interface SessionMessageEntry extends SessionEntryBase {
	type: "message";
	message: AgentMessage;
}

export interface ThinkingLevelChangeEntry extends SessionEntryBase {
	type: "thinking_level_change";
	thinkingLevel?: string | null;
}

export interface ModelChangeEntry extends SessionEntryBase {
	type: "model_change";
	/** Model in "provider/modelId" format */
	model: string;
	/** Role: "default", "smol", "slow", etc. Undefined treated as "default" */
	role?: string;
}

export interface ServiceTierChangeEntry extends SessionEntryBase {
	type: "service_tier_change";
	serviceTier: ServiceTierByFamily | null;
}

export interface CompactionEntry<T = unknown> extends SessionEntryBase {
	type: "compaction";
	summary: string;
	shortSummary?: string;
	firstKeptEntryId: string;
	tokensBefore: number;
	/** Last entry covered by native replay; later entries may precede the compaction record. */
	providerReplayThroughEntryId?: string;
	/** Extension-specific data (e.g., ArtifactIndex, version markers for structured compaction) */
	details?: T;
	/** Hook-provided data to persist across compaction */
	preserveData?: Record<string, unknown>;
	/** True if generated by an extension, undefined/false if pi-generated (backward compatible) */
	fromExtension?: boolean;
	/**
	 * Dead-end warning from the post-pass progress guard: the pass completed
	 * but freed too little for maintenance to continue. Rendered on the
	 * compaction divider.
	 */
	warning?: string;
}

export interface BranchSummaryEntry<T = unknown> extends SessionEntryBase {
	type: "branch_summary";
	fromId: string;
	summary: string;
	/** Extension-specific data (not sent to LLM) */
	details?: T;
	/** True if generated by an extension, false if pi-generated */
	fromExtension?: boolean;
}

export interface CustomMessageEntry<T = unknown> extends SessionEntryBase {
	type: "custom_message";
	customType: string;
	content: string | (TextContent | ImageContent)[];
	details?: T;
	display: boolean;
	/** Who initiated this message for billing/attribution semantics. */
	attribution?: MessageAttribution;
}

export interface CustomEntry<T = unknown> extends SessionEntryBase {
	type: "custom";
	customType: string;
	data?: T;
}

export interface LabelEntry extends SessionEntryBase {
	type: "label";
	targetId: string;
	label: string | undefined;
}

export interface TitleChangeEntry extends SessionEntryBase {
	type: "title_change";
	title: string;
	previousTitle?: string;
	source: "auto" | "user";
	trigger?: string;
}

export interface TtsrInjectionEntry extends SessionEntryBase {
	type: "ttsr_injection";
	/** Names of rules that were injected */
	injectedRules: string[];
}

export interface SessionInitEntry extends SessionEntryBase {
	type: "session_init";
	/** System prompt blocks exactly as sent to the model; files written before blocks were kept store one joined string. */
	systemPrompt: string[] | string;
	/** Initial task/user message */
	task: string;
	/** Tools available to the agent */
	tools: string[];
	/** Output schema if structured output was requested */
	outputSchema?: unknown;
}

export interface ModeChangeEntry extends SessionEntryBase {
	type: "mode_change";
	/** Current mode name, or "none" when exiting a mode */
	mode: string;
	/** Optional mode-specific data (e.g. plan file path) */
	data?: Record<string, unknown>;
}

/**
 * Durable context-reset marker recorded by an in-place `/clear`. It carries no
 * payload — its presence on the branch means every entry before it was dropped
 * from the model context, so context assembly and compaction start after the
 * latest one. The full pre-reset history stays on disk for transcript export.
 */
export interface ResetBoundaryEntry extends SessionEntryBase {
	type: "reset_boundary";
}

/** Replacement notice for one tool-result message blanked by automatic pruning. */
export interface ToolResultPruneTarget {
	/** Id of the `message` entry whose result this notice replaces. */
	entryId: string;
	/** Exact placeholder text shown in place of the original result. */
	notice: string;
}

/**
 * Append-only overlay recorded by automatic tool-result pruning. Never rewrites
 * or replaces the journal: raw message bytes stay intact and readers project the
 * blanked result only on paths that contain this entry.
 */
export interface ToolResultPruneEntry extends SessionEntryBase {
	type: "tool_result_prune";
	/** Prune timestamp copied onto every projected target result. */
	prunedAt: number;
	targets: ToolResultPruneTarget[];
}

export interface CustomCompactionSessionEntries {}

export type SessionEntry =
	| SessionMessageEntry
	| ThinkingLevelChangeEntry
	| ModelChangeEntry
	| ServiceTierChangeEntry
	| CompactionEntry
	| BranchSummaryEntry
	| CustomEntry
	| CustomMessageEntry
	| LabelEntry
	| TitleChangeEntry
	| TtsrInjectionEntry
	| SessionInitEntry
	| ModeChangeEntry
	| ResetBoundaryEntry
	| ToolResultPruneEntry
	| CustomCompactionSessionEntries[keyof CustomCompactionSessionEntries];

export interface ReadonlySessionManager {
	getBranch(leafId?: string | null): SessionEntry[];
	getEntry(id: string): SessionEntry | undefined;
}
